/// يجمع قواعد المحاور الثلاثة في نص واحد: النمط + المستوى + المنصة (تحت مستوى
/// «تنسيق منصة» فقط)، مع تخصيص الشذرة الذي يقدَّم على قواعد المنصة العامة.
pub(crate) fn compose_rules(style: &str, intervention: &str, platform: Option<&str>) -> String {
    let mut rules = format!(
        "{}\n{}",
        style_rules(style),
        intervention_rules(intervention)
    );
    // بصمة الإيقاع: المستويان الإيقاعيان فقط (مقتضى مستقل عن المنصة، والاثنان
    // لا يتقاطعان مع «تنسيق منصة» في القائمة أصلًا)
    if intervention == LEVEL_RHYTHM || intervention == LEVEL_RHYTHM_DOTTED {
        rules.push('\n');
        rules.push_str(RHYTHM_FINGERPRINT_CONTRACT);
    }
    if intervention == LEVEL_PLATFORM {
        let p = platform.unwrap_or("").trim();
        rules.push('\n');
        rules.push_str(if style == STYLE_FRAGMENT {
            fragment_platform_rules(p)
        } else {
            platform_rules(p)
        });
        // وجهة سابستاك (مقالًا أو نوتًا): عقد الكسر يُحقن في كل نداء إبداعي
        if is_substack(p) {
            rules.push('\n');
            rules.push_str(SUBSTACK_BREATH_CONTRACT);
            // خريطة الرموز اليدوية لا تُحقن مع الشذرة: فاصلها مضبوط أصلًا
            // (رقم أو نقطة عارية) وقاعدتها الصارمة تمنع أي علامة مستحدثة
            // حول المنعطف — حقن رموز جديدة هنا يصادم تلك القاعدة
            if style != STYLE_FRAGMENT {
                rules.push('\n');
                rules.push_str(SUBSTACK_MANUAL_MARKERS_CONTRACT);
            }
        }
    }
    if style == STYLE_FRAGMENT {
        rules.push('\n');
        rules.push_str(FRAGMENT_RULES);
    }
    rules
}

// ---------- لوحة التنويعات: رافعة كثافة الكسر (تشخيص v3.5) ----------
// العطب المرصود: التعليمة العامة (variation_note) كانت نصًا واحدًا مطابقًا
// حرفيًا للمحاولتين ٢ و٣ (لا فرق سوى الرقم)، فتقاربت النتائج أو تطابقت. وعلى
// النصوص قصيرة الجُمل، «موضع» الكسر ضيق أصلًا (كل جملة قصيرة سطر واحد)، فلا
// مجال لتنويع حقيقي بالموضع وحده. الحل: لكل تنويعة من الثلاث رافعة صريحة
// ومختلفة بنيويًا — كثافة الكسر (تجميع/تفريد/وسط) لا موضعه فقط، فيظهر تباين
// حقيقي حتى حين تخنق قصر الجُمل حرية الموضع.
pub(crate) fn variation_slot_lever(slot: u8) -> &'static str {
    match slot {
        0 => "رافعة هذه التنويعة: كثافة كسر منخفضة. اجمع الجمل القصيرة المتقاربة معنًى في السطر الواحد حين يسمح المعنى، ولا تكسر إلا عند منعطف حقيقي (بل/لكن/غير أن/نقطتان/شرطة) أو نهاية فكرة كبرى. النتيجة سطور أقل عددًا وأطول قليلًا.",
        1 => "رافعة هذه التنويعة: كثافة كسر عالية. افرد كل جملة أو وحدة معنى — وإن قصرت — في سطر مستقل، ووزّع وقفة بعد كل نَفَس قصير. النتيجة سطور أكثر عددًا وأقصر.",
        _ => "رافعة هذه التنويعة: كثافة كسر وسط بين التجميع والتفريد — لا أقصى دمج كالتنويعة الأولى ولا أقصى تفكيك كالثانية، بل توازن مقروء بلا انقطاع متكرر ولا امتداد طويل.",
    }
}

// قفل مطلق يرافق كل تنويعة: يمنع أن يتحول التنوّع في الكسر إلى تصرف بالكلمات،
// ويُلزم بأن يكون الفرق بين الثلاث واضحًا للعين لا إزاحة كلمة مجهرية
pub(crate) const VARIATIONS_LOCK: &str = "قفل مطلق للتنويعات الثلاث: الكلمات والمعنى وترتيب الجُمل يتطابق حرفًا بحرف بين التنويعات الثلاث جميعًا — لا كلمة تُضاف أو تُحذف أو تُبدَّل، ولا جملة تُعاد ترتيبها. الفارق الوحيد المسموح بينها كثافة كسر السطر ومواضعه. التزم برافعة هذه التنويعة بوضوح تام حتى يظهر فرق بصري واضح للعين بين التنويعات الثلاث — لا إزاحة كلمة مجهرية بين نتيجة وأخرى.";

/// تعليمة التنويع بين الضغطات: رقم المحاولة يدخل نص الطلب دائمًا حتى تختلف
/// البصمة عند المزود، وتعليمة الاختلاف الصريحة تُضاف من المحاولة الثانية.
pub(crate) fn variation_note(attempt: u64, style: &str) -> String {
    let mut note = format!("رقم المحاولة لهذا النص وهذه الإعدادات: {}.", attempt);
    if attempt > 1 {
        note.push_str(" أنتج توزيعًا يختلف عن المحاولات السابقة في الفواصل والوقفات وطول المقاطع، مع بقاء المعنى والكلمات كما هي.");
        if style == STYLE_FRAGMENT {
            note.push_str(" استثناء: الشذرة الواحدة غير القابلة للاختزال (سطر واحد بلا التفاتة) لا تنويع فيها — إعادة الشكل نفسه حينها صواب، ولا تُشوَّه شذرة مُحكَمة لافتعال اختلاف.");
        }
    }
    note
}

