// هيكل وضع «شَذْب» — محجوز ومعطَّل (المرحلة 2): لا واجهة ولا عقد ولا نداء
// نموذج ولا زر. يُحمَّل أخيرًا بعد القشرة ونسق، وكل جسده داخل درع: فشله
// الكامل — تحميلًا أو تنفيذًا — لا يمس نسق بشيء.
//
// القواعد الملزمة يوم البناء:
// - يستهلك window.NasaqShell وwindow.NasaqPrune حصرًا — لا يلمس دوال وضع
//   التنسيق ولا حالته ولا عناصر DOM الخاصة به.
// - عقوده النصية في src-tauri/src/shadhb حصرًا يوم تُكتب — لا هنا.
// - يبقى خلف NasaqShell.flags.shadhbEnabled: ما دام false فلا أثر مرئي
//   ولا سلوكي له إطلاقًا، والواجهة تطابق ما قبله تمامًا.
(() => {
  try {
    const shell = window.NasaqShell;
    // المفتاح معطَّل افتراضيًا — الخروج الصامت هو كل سلوك هذه المرحلة
    if (!shell || !shell.flags || shell.flags.shadhbEnabled !== true) return;
    // (المرحلة القادمة: تهيئة وضع شَذْب تبدأ من هنا حصرًا)
  } catch (err) {
    // درع العزل الأمامي: تعطّل شَذْب يُسجَّل ويُعزَل — نسق يواصل عمله كاملًا
    console.error("تعطّل هيكل شَذْب وعُزل بأمان:", err);
  }
})();
